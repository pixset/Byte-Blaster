// Один набор на всю игру: и на выбор цвета в мультиплеере, и на аватары в
// профиле. Раньше эти два места держали СВОИ списки — в лобби была одна
// десятка оттенков, в профиле другая восьмёрка, — и робот, которого игрок
// выбрал аватаром, в комнате выглядел иначе. Теперь список здесь один, а обе
// стороны читают его отсюда.
//
// Десять роботов: семь цветов радуги плюс розовый, чёрный и коричневый.
// Больше в игре нет и не появляется само собой — новый цвет нужно дописать
// сюда, и он сразу окажется и в лобби, и в профиле.
//
// Цвет задаётся как {h,s,l} — из него window.robotPalette (game.js) выводит всю
// палитру корпуса: корпус, тень, визор. Поэтому светлота подобрана не «как
// красивее в кружке выбора», а так, чтобы читался сам робот: слишком светлый
// оттенок делает тёмные части корпуса белёсыми, слишком тёмный — сливает
// робота с фоном уровня.
(function () {
  'use strict';

  window.BB_ROBOTS = [
    // Первым идёт синий: это цвет самого ЮНИТ-7, и он же достаётся игроку по
    // умолчанию — и в лобби, и аватаром в профиле.
    { id: 'blue',   hsl: { h: 218, s: 88, l: 52 } },
    { id: 'red',    hsl: { h: 0,   s: 88, l: 52 } },
    { id: 'orange', hsl: { h: 26,  s: 95, l: 52 } },
    { id: 'yellow', hsl: { h: 48,  s: 95, l: 52 } },
    { id: 'green',  hsl: { h: 128, s: 72, l: 44 } },
    { id: 'cyan',   hsl: { h: 194, s: 90, l: 55 } },   // голубой
    { id: 'violet', hsl: { h: 272, s: 72, l: 56 } },
    { id: 'pink',   hsl: { h: 335, s: 90, l: 68 } },
    // Чёрный и коричневый — не «оттенки радуги», поэтому насыщенность у них
    // низкая, а светлота выше, чем кажется нужным: палитра ещё затемняет
    // корпус, и на чёрном фоне уровня совсем тёмный робот пропадает.
    { id: 'black',  hsl: { h: 220, s: 12, l: 30 } },
    { id: 'brown',  hsl: { h: 24,  s: 48, l: 36 } },
  ];

  /** Цвет по индексу; за границами списка — первый. */
  window.bbRobotColor = function (i) {
    var list = window.BB_ROBOTS;
    var n = Number(i);
    return (list[n] || list[0]).hsl;
  };

  /** Индекс по id ('blue'); неизвестный id — 0. */
  window.bbRobotIndex = function (id) {
    var list = window.BB_ROBOTS;
    for (var i = 0; i < list.length; i++) if (list[i].id === id) return i;
    return 0;
  };
})();
