// Stamp a version string everywhere the game/build reads it from.
// Usage: node build/set-version.js 1.2.3   (run from the project root)
//   - package.json  "version"        -> Windows .exe file version (electron-packager)
//   - assets/version.js BB_VERSION   -> the in-game "vX.Y.Z" menu tag
// android-build.ps1 reads package.json to stamp the .apk versionName/versionCode.
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
let v = (process.argv[2] || '').trim();
if (!/^\d+(\.\d+){0,3}([-+].+)?$/.test(v)) {
  console.error('[set-version] invalid version: "' + v + '" (expected e.g. 1.2.3)');
  process.exit(1);
}

const pkgPath = path.join(root, 'package.json');
const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
pkg.version = v;
fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');

const verJs =
  '// Game version - regenerated by build/build.bat at build time (and kept here as a\n' +
  '// sensible default for `npm start` / opening index.html directly). The main menu\n' +
  '// reads window.BB_VERSION to show "vX.Y.Z" in the corner.\n' +
  'window.BB_VERSION = "' + v + '";\n';
fs.writeFileSync(path.join(root, 'assets', 'version.js'), verJs);

console.log('[set-version] version set to ' + v);
