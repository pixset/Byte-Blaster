// Stamp the build TYPE everywhere the game and the build read it from.
// The counterpart of set-version.js.
//
// Тип сборки — это только маркировка канала (что за билд у игрока на руках).
// Он больше не решает, сколько контента доступно: полную игру открывает
// лицензия на аккаунте, а без лицензии в любой сборке играется первый мир.
//
// Usage (from the project root):
//   node build/set-edition.js dev
//   node build/set-edition.js beta
//   node build/set-edition.js release
//   node build/set-edition.js demo "https://pixset-studio.github.io/store"
//   node build/set-edition.js alpha "" 5     (первый мир урезан до 5 уровней)
//
// Writes assets/edition.js, loaded before every other script:
//   window.BB_BUILD_TYPE   — канал сборки, показывается рядом с версией
//   window.BB_FREE_LEVELS  — сколько уровней открыто без лицензии
//   window.BB_STORE_URL    — куда вести за полной версией
const fs = require('fs');
const path = require('path');

const TYPES = ['dev', 'demo', 'pre-alpha', 'alpha', 'beta', 'release'];

const root = path.resolve(__dirname, '..');
const editionPath = path.join(root, 'assets', 'edition.js');

const type = (process.argv[2] || '').trim().toLowerCase();
if (TYPES.indexOf(type) === -1) {
  console.error('[set-edition] invalid build type: "' + type + '" (expected ' + TYPES.join(' | ') + ')');
  process.exit(1);
}

// Keep whatever URL / level cap is already configured unless this call passes a
// new one, so switching types during a "build both" run doesn't wipe the store
// link the developer set once.
const prev = readPrevious();
const url = process.argv[3] !== undefined ? String(process.argv[3]).trim() : prev.url;
const levelsArg = process.argv[4];
const levels = levelsArg !== undefined ? parseInt(levelsArg, 10) : prev.levels;
if (!(levels >= 1 && levels <= 110)) {
  console.error('[set-edition] invalid free level cap: "' + levelsArg + '" (expected 1-110)');
  process.exit(1);
}
if (url && !/^https?:\/\//i.test(url)) {
  console.error('[set-edition] invalid store url: "' + url + '" (expected http(s)://…)');
  process.exit(1);
}

function readPrevious() {
  const out = { url: 'https://pixset-studio.github.io/store', levels: 10 };
  try {
    const src = fs.readFileSync(editionPath, 'utf8');
    // Старые имена читаем тоже — чтобы обновление проекта ничего не потеряло.
    const u = src.match(/BB_(?:STORE|DEMO)_URL\s*=\s*"([^"]*)"/);
    const l = src.match(/BB_(?:FREE|DEMO)_LEVELS\s*=\s*(\d+)/);
    if (u) out.url = u[1];
    if (l) out.levels = parseInt(l[1], 10);
  } catch (e) { /* first run — defaults are fine */ }
  return out;
}

const js =
  '// Build type - regenerated by build/set-edition.js at build time (and kept\n' +
  '// here as the sensible default for `npm start` / opening index.html directly).\n' +
  '//\n' +
  '// Тип сборки — только маркировка канала. Объём контента определяет лицензия\n' +
  '// на аккаунте Pixset Studio, а не тип билда.\n' +
  '//\n' +
  '//   BB_BUILD_TYPE  "dev" | "demo" | "pre-alpha" | "alpha" | "beta" | "release"\n' +
  '//   BB_FREE_LEVELS сколько уровней приключения открыто без лицензии\n' +
  '//   BB_STORE_URL   куда ведёт кнопка «купить полную версию»\n' +
  'window.BB_BUILD_TYPE = "' + type + '";\n' +
  'window.BB_FREE_LEVELS = ' + levels + ';\n' +
  'window.BB_STORE_URL = "' + url + '";\n';

fs.writeFileSync(editionPath, js, 'utf8');
console.log('[set-edition] build type set to ' + type +
            ' (' + levels + ' free levels, store: ' + (url || 'none') + ')');
